    /// <summary>
    /// Textos de la pantalla de Configuración en 7 idiomas:
    /// es, en, fr, pt, de, it, zh. El idioma elegido se guarda en Preferences.
    /// Para traducir otra pantalla, agrega sus claves en cada diccionario
    /// y usa Textos.T("clave") en lugar del texto fijo.
    /// </summary>
    public static class Textos
    {
        private const string ClavePreferencia = "Idioma";

        public static readonly string[] CodigosSoportados = { "es", "en", "fr", "pt", "de", "it", "zh" };

        public static string IdiomaActual
        {
            get
            {
                string guardado = Preferences.Default.Get(ClavePreferencia, "es");
                return CodigosSoportados.Contains(guardado) ? guardado : "es";
            }
            set => Preferences.Default.Set(ClavePreferencia, CodigosSoportados.Contains(value) ? value : "es");
        }

        public static string T(string clave)
        {
            if (Tabla(IdiomaActual).TryGetValue(clave, out var valor)) return valor;
            return _es.TryGetValue(clave, out var respaldo) ? respaldo : clave;
        }

        private static Dictionary<string, string> Tabla(string codigo) => codigo switch
        {
            "en" => _en,
            "fr" => _fr,
            "pt" => _pt,
            "de" => _de,
            "it" => _it,
            "zh" => _zh,
            _ => _es
        };

